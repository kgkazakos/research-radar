"""
research-radar · CPR Orbital Tool 22
Basic usage example — rule-based scan on text input.
"""

from pathlib import Path

from research_radar.models import SignalStrength, TrendReport
from research_radar.reporter import render_markdown, render_plain
from research_radar.scanner import build_signals, scan_text

# ---------------------------------------------------------------------------
# 1. Rule-based scan on a text file
# ---------------------------------------------------------------------------

sample_text = """
Thematic analysis remains the dominant method in UX research, but teams are increasingly
pairing it with AI-assisted pre-coding using LLMs like Claude and GPT-4.

Dovetail and Maze have both shipped AI features in Q2 2025, with Dovetail's automated
theme clustering now in general availability. UserTesting added Figma integration for
unmoderated prototype sessions.

A CHI 2026 preprint found that synthetic participants generated by LLMs can approximate
some behavioral patterns of real users — useful for hypothesis generation, not validation.

User trust in AI recommendations erodes faster after a single bad experience compared to
human recommendations, according to longitudinal diary study data from three B2C products.

Research ops teams are growing at companies with high UX maturity, while others are
consolidating headcount and leaning on automation tools to fill the gap.
"""

print("=" * 60)
print("EXAMPLE 1: Rule-based scan on text")
print("=" * 60)

results = scan_text(sample_text, domain="AI in UX research")
print(f"Scan results: {len(results)} sentence-level hits\n")

signals = build_signals(results, domain="AI in UX research", min_strength=SignalStrength.LOW)
print(f"Signals built: {len(signals)}")
for sig in signals:
    print(f"  [{sig.strength.value.upper():6}] {sig.category.value:12} | {sig.title}")

# ---------------------------------------------------------------------------
# 2. Build and render a TrendReport
# ---------------------------------------------------------------------------

print("\n" + "=" * 60)
print("EXAMPLE 2: TrendReport → plain text")
print("=" * 60)

report = TrendReport(
    domain="AI in UX research",
    signals=signals,
    narrative=(
        "AI-assisted tooling is reshaping the methodological stack faster than teams "
        "can develop governance frameworks for it. The growing gap between practitioners "
        "who have integrated LLMs into their workflow and those who haven't represents "
        "a skills bifurcation worth monitoring. The team should revisit how we validate "
        "AI-assisted coding against human coders — what threshold counts as 'good enough'?"
    ),
)

print(render_plain(report))

# ---------------------------------------------------------------------------
# 3. Render as markdown
# ---------------------------------------------------------------------------

print("\n" + "=" * 60)
print("EXAMPLE 3: Markdown output (first 1000 chars)")
print("=" * 60)

md = render_markdown(report)
print(md[:1000] + "\n…")

# ---------------------------------------------------------------------------
# 4. JSON serialization
# ---------------------------------------------------------------------------

print("\n" + "=" * 60)
print("EXAMPLE 4: JSON round-trip")
print("=" * 60)

import json

serialized = report.to_dict()
print(f"Keys: {list(serialized.keys())}")
print(f"Signal count from JSON: {serialized['signal_count']}")

restored = TrendReport.from_dict(serialized)
print(f"Restored domain: {restored.domain}")
print(f"Restored signals: {restored.signal_count}")
